/**
 * Generated .conf content. Setting names and values follow real Splunk; the comments and the
 * selection of settings are our own abbreviation of the shipped defaults.
 */

const header = (version: string, conf: string) =>
  `#   Version ${version}\n#\n# System defaults for ${conf}.\n# DO NOT EDIT THIS FILE. Put local changes in $SPLUNK_HOME/etc/system/local/${conf}\n# or in an app's local directory. Changes here are overwritten on upgrade.\n\n`;

/** A splunk-encrypted secret placeholder ($7$...), stable per host and label. */
function secret(p: HostProfile, label: number): string {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  let s = '$7$';
  for (let i = 0; i < 56; i++) s += chars[mix32(p.hash, label, i) % 64];
  return s + '==';
}

