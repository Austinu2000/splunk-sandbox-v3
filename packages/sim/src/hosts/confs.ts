const CLUSTER_INDEXES = ['os', 'app', 'network'];

export function clusterIndexesConf(): string {
  return (
    CLUSTER_INDEXES.map(
      (i) =>
        `[${i}]\nhomePath = $SPLUNK_DB/${i}/db\ncoldPath = $SPLUNK_DB/${i}/colddb\nthawedPath = $SPLUNK_DB/${i}/thaweddb\nrepFactor = auto\nfrozenTimePeriodInSecs = ${i === 'network' ? 7776000 : 31536000}\n`,
    ).join('\n') + '\n'
  );
}
export const clusterIndexes = () => [...CLUSTER_INDEXES];

/** Parsing settings distributed to the indexer cluster (the parsing tier for forwarder data). */
export function clusterPropsConf(): string {
  return [
    '[app:log]',
    'SHOULD_LINEMERGE = false',
    'LINE_BREAKER = ([\\r\\n]+)\\d{4}-\\d{2}-\\d{2}T',
    'TIME_PREFIX = ^',
    'TIME_FORMAT = %Y-%m-%dT%H:%M:%S.%3N%Z',
    'MAX_TIMESTAMP_LOOKAHEAD = 30',
    'TRUNCATE = 20000',
    '',
    '[access_combined]',
    'SHOULD_LINEMERGE = false',
    '',
    '[mysqld]',
    'SHOULD_LINEMERGE = false',
    'TIME_PREFIX = ^',
    '',
  ].join('\n');
}

/** The cluster bundle: files under manager-apps/ on the manager, peer-apps/ on each indexer. */
export function clusterBundle(): Record<string, string> {
  return {
    '_cluster/local/indexes.conf': clusterIndexesConf(),
    '_cluster/local/props.conf': clusterPropsConf(),
  };
}

/** Files in etc/system/local for this host. */
export function systemLocal(world: World, p: HostProfile): Record<string, string> {
  const files: Record<string, string> = {};
  const role = p.role;
  const server = [
    `[general]`,
    `serverName = ${p.hostname}`,
    `pass4SymmKey = ${secret(p, 1)}`,
    ``,
    `[sslConfig]`,
    `sslPassword = ${secret(p, 2)}`,
    ``,
  ];
  if (role === 'universal_forwarder') {
    files['server.conf'] = server.join('\n');
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n`;
    return files;
  }

  const cm = `https://cm01.${DOMAIN}:8089`;
  if (role === 'indexer') {
    server.push(
      '[clustering]',
      'mode = peer',
      `manager_uri = ${cm}`,
      `pass4SymmKey = ${secret(p, 3)}`,
      '',
      '[replication_port://9887]',
      '',
    );
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n\n[splunktcp://9997]\ndisabled = 0\n`;
  } else if (role === 'cluster_manager') {
    server.push(
      '[clustering]',
      'mode = manager',
      'replication_factor = 3',
      'search_factor = 2',
      `pass4SymmKey = ${secret(p, 3)}`,
      'cluster_label = corp_idx_cluster',
      '',
    );
  } else if (role === 'search_head') {
    server.push(
      '[clustering]',
      'mode = searchhead',
      `manager_uri = ${cm}`,
      `pass4SymmKey = ${secret(p, 3)}`,
      '',
    );
  } else if (role === 'license_manager') {
    server.push('[license]', 'active_group = Enterprise', '');
  } else if (role === 'heavy_forwarder') {
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n\n[splunktcp://9997]\ndisabled = 0\n`;
  } else if (role === 'deployment_server') {
    files['serverclass.conf'] = serverclassConf(world);
  }
  if (role !== 'license_manager') server.push('[license]', `manager_uri = https://lm01.${DOMAIN}:8089`, '');
  files['server.conf'] = server.join('\n');
  if (!files['inputs.conf']) files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n`;

  // Everything but indexers forwards its own internal logs to the site's indexers.
  if (role !== 'indexer') {
    const group = outputGroupName(p.site, 'indexers');
    const servers = outputTargets(world, p.site, 'indexers').map((n) => `${n.hostname}.${DOMAIN}:9997`);
    files['outputs.conf'] =
      `[indexAndForward]\nindex = false\n\n[tcpout]\ndefaultGroup = ${group}\nforwardedindex.filter.disable = true\nindexAndForward = false\n\n[tcpout:${group}]\nserver = ${servers.join(', ')}\n`;
  }
  return files;
}

/** Apps that ship with the product (not deployed by the DS). */
export function builtinApps(p: HostProfile): string[] {
  if (p.splunk?.product === 'universal_forwarder')
    return [
      'SplunkUniversalForwarder',
      'introspection_generator_addon',
      'journald_input',
      'learned',
      'search',
      'splunk_httpinput',
      'splunk_internal_metrics',
    ];
  const apps = [
    'introspection_generator_addon',
    'journald_input',
    'launcher',
    'learned',
    'search',
    'splunk_httpinput',
    'splunk_instrumentation',
    'splunk_internal_metrics',
  ];
  if (p.role === 'search_head' || p.role === 'cluster_manager')
    apps.push('splunk_monitoring_console', 'splunk_secure_gateway');
  return apps.sort();
}
